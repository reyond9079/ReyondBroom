inline Document applyPreset(Document doc,const CharacterPreset& preset) {
  doc.name = preset.name;
  doc.seed = 0;
  doc.values = {};
  constexpr MorphIndex features[]{JawWidth,ChinHeight,NoseWidth,NoseBridge,EyeSpacing,EyeTilt,
                                   LipFullness,CheekFullness,HeadWidth,HeadHeight,MouthWidth};
  for (std::size_t i=0; i<std::size(features); ++i) doc.values[features[i]] = preset.features[i];
  constexpr MorphIndex build[]{Height,BodyFat,Muscle,ShoulderWidth,EyeSize,ChinWidth};
  for (std::size_t i=0; i<std::size(build); ++i) doc.values[build[i]] = preset.build[i];
  for (const auto& [shape,amount] : preset.sculpt) doc.values[shape] = amount;
  doc.outfit = preset.outfit;
  doc.hairstyle = preset.hair;
  doc.footwear = 0;
  doc.headwear = 1;
  doc.hat = true;
  doc.complexion = preset.complexion;
  doc.faceProfile = preset.profile;
  doc.bodyProfile = std::clamp(1.35*preset.profile,-1.,1.);
  doc.faceTemplate = preset.face;
  doc.eyebrow = preset.brows;
  doc.expression = 0;
  doc.beard = preset.beard;
  doc.skin = preset.skin;
  doc.eyes = preset.eyes;
  doc.hairColor = preset.hairColor;
  doc.hairVolume = preset.hairVolume;
  doc.hairLength = preset.hairLength;
  doc.faceAsymmetry = preset.asymmetry;
  doc.hairline = preset.hairline;
  return doc;
}
