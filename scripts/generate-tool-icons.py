"""Generate native line icons from vendored Lucide SVGs (requires svgpathtools)."""
from pathlib import Path
from svgpathtools import svg2paths, Line

root = Path(__file__).resolve().parents[1]
names = ['mouse-pointer-2', 'box', 'scissors', 'waypoints', 'git-commit-horizontal',
         'square', 'grid-2x2', 'rotate-3d', 'spline', 'scaling', 'fold-horizontal',
         'lock-keyhole', 'ratio', 'sculpt', 'bend', 'polygon-cut', 'polygon-spawn', 'play', 'pause']
out = ['// Generated by scripts/generate-tool-icons.py; do not edit point data.',
       '// Lucide ISC / Feather MIT; see assets/lucide/LICENSE.',
       'namespace FteIcons {',
       'struct Stroke { const ImVec2* points; int count; };']
for index, name in enumerate(names):
    paths, _ = svg2paths(str(root / ('assets/model-icons' if name in ('play','pause') else 'assets/lucide') / (name+'.svg')))
    strokes = []
    for path in paths:
        for part in path.continuous_subpaths():
            points = [part.start]
            for segment in part:
                steps = 1 if isinstance(segment, Line) else 24
                points += [segment.point(i/steps) for i in range(1, steps+1)]
            assert all(-1 <= p.real <= 25 and -1 <= p.imag <= 25 for p in points)
            ident = f'points_{index}_{len(strokes)}'
            out.append('static const ImVec2 '+ident+'[] = {' + ','.join(
                f'{{{p.real:.5f}f,{p.imag:.5f}f}}' for p in points) + '};')
            strokes.append(f'{{{ident},{len(points)}}}')
    out.append(f'static const Stroke icon_{index}[] = {{'+','.join(strokes)+'};')
out += ['struct Icon { const Stroke* strokes; int count; };',
        'static const Icon icons[] = {' + ','.join(
            f'{{icon_{i},int(sizeof(icon_{i})/sizeof(Stroke))}}' for i in range(len(names)))+'};',
        '''static bool button(const char* id,int index,ImVec2 size) {
  if(index<0||index>=int(sizeof(icons)/sizeof(icons[0])))index=0;
  const auto p=ImGui::GetCursorScreenPos();bool clicked=ImGui::Button(id,size);
  const float extent=std::min(size.x,size.y)*.68f,scale=extent/24.f;
  const ImVec2 origin{p.x+(size.x-extent)*.5f,p.y+(size.y-extent)*.5f};
  auto draw=ImGui::GetWindowDrawList();const auto color=ImGui::GetColorU32(ImGuiCol_Text);
  for(int i=0;i<icons[index].count;++i){const auto& stroke=icons[index].strokes[i];
    draw->PathClear();for(int j=0;j<stroke.count;++j)draw->PathLineTo({origin.x+stroke.points[j].x*scale,origin.y+stroke.points[j].y*scale});
    draw->PathStroke(color,0,std::max(1.f,scale*2));
  }
  return clicked;
}
}''']
(root/'native/ftebroom_tool_icons.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
